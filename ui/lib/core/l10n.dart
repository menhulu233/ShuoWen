  static L10n fromSetting(String? setting) {
    final value = (setting ?? 'auto').toLowerCase();
    if (value == 'zh' || value == 'zh-hant') return const L10n('zh');
    if (value == 'ja') return const L10n('ja');
    if (value == 'ko') return const L10n('ko');
    if (value == 'en') return const L10n('en');
    final system = PlatformDispatcher.instance.locale.languageCode;
    if (system == 'zh') return const L10n('zh');
    if (system == 'ja') return const L10n('ja');
    if (system == 'ko') return const L10n('ko');
    return const L10n('en');
  }

